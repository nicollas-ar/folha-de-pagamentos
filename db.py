import psycopg
from psycopg.rows import dict_row

from flask import current_app, g


SCHEMA = """
CREATE TABLE IF NOT EXISTS employees (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    department TEXT NOT NULL,
    job_title TEXT NOT NULL,
    base_salary DOUBLE PRECISION NOT NULL CHECK(base_salary >= 0),
    active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin', 'rh', 'gestor', 'funcionario')),
    employee_id INTEGER UNIQUE REFERENCES employees(id),
    active INTEGER NOT NULL DEFAULT 1,
    clearance INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS payrolls (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id),
    reference TEXT NOT NULL,
    overtime_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    overtime_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
    bonus DOUBLE PRECISION NOT NULL DEFAULT 0,
    other_earnings DOUBLE PRECISION NOT NULL DEFAULT 0,
    deductions DOUBLE PRECISION NOT NULL DEFAULT 0,
    gross_pay DOUBLE PRECISION NOT NULL,
    net_pay DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL DEFAULT 'rascunho'
        CHECK(status IN ('rascunho', 'aprovada', 'fechada')),
    created_by INTEGER NOT NULL REFERENCES users(id),
    approved_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(employee_id, reference)
);
"""


def get_db():
    if "db" not in g:
        url = current_app.config["DATABASE_URL"]
        if not url:
            raise RuntimeError("Configure DATABASE_URL com a conexão PostgreSQL do Neon.")
        g.db = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)
    return g.db


def close_db(_error=None):
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


def init_db():
    db = get_db()
    # Serializa inicializações concorrentes no PostgreSQL.
    db.execute("SELECT pg_advisory_xact_lock(74219831)")
    for statement in SCHEMA.split(";"):
        if statement.strip():
            db.execute(statement)
    db.commit()
